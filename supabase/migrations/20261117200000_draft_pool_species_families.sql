-- Family keys used by the species clause. Change the rule here only.
-- Keys from draft_pool_species_families for the resolved pokepedia id; unknown id ->
-- 'species:<species_name>' from pokepedia_pokemon, then public.pokemon. Null = unknown
-- (the clause is skipped for that Pokemon rather than guessing).
create or replace function public.draft_pool_species_keys(
  p_pokepedia_id integer,
  p_pokemon uuid default null
)
returns text[]
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_id integer;
  v_keys text[];
  v_species text;
begin
  v_id := coalesce(p_pokepedia_id, public.draft_pool_resolve_pokepedia_id(p_pokemon));

  if v_id is not null then
    select array_agg(f.family_key order by f.family_key) into v_keys
    from public.draft_pool_species_families f
    where f.pokepedia_id = v_id;
    if cardinality(v_keys) > 0 then
      return v_keys;
    end if;
  end if;

  v_species := nullif(
    lower(btrim(coalesce(
      (select pp.species_name from public.pokepedia_pokemon pp where pp.id = v_id),
      (select p.species_name from public.pokemon p where p.id = p_pokemon)
    ))),
    ''
  );

  if v_species is null then
    return null;
  end if;
  return array['species:' || v_species];
end;
$$;

-- Single canonical family key (min of draft_pool_species_keys) for display / back-compat.
-- The species clause itself compares the keys ARRAY (overlap), not this value.
create or replace function public.draft_pool_species_key(
  p_pokepedia_id integer,
  p_pokemon uuid default null
)
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select min(k)
  from unnest(public.draft_pool_species_keys(p_pokepedia_id, p_pokemon)) as k
$$;

-- SPECIES_CLAUSE when the candidate's family keys overlap any roster member's keys
-- (p_drop_pokemon excluded). Detail: species=<display name of the conflicting roster Pokemon>.
-- p_defer_identity_to_unique_index: for draft_picks writers; when the candidate is already an
-- active pick in the season, the existing uq_season_pokemon_unique path raises its own code.
create or replace function public.draft_pool_assert_species_clause(
  p_season_id uuid,
  p_team_id uuid,
  p_pokemon uuid,
  p_pokepedia_id integer default null,
  p_drop_pokemon uuid default null,
  p_defer_identity_to_unique_index boolean default false
)
returns void
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_keys text[];
  v_conflict uuid;
  v_display text;
begin
  if p_defer_identity_to_unique_index and exists (
    select 1
    from public.draft_picks dp
    where dp.season_id = p_season_id
      and dp.pokemon_id = p_pokemon
      and dp.status = 'active'
  ) then
    return;
  end if;

  v_keys := public.draft_pool_species_keys(
    coalesce(p_pokepedia_id, public.draft_pool_resolve_pokepedia_id(p_pokemon)),
    p_pokemon
  );

  if v_keys is null or cardinality(v_keys) = 0 then
    return;
  end if;

  select r.pokemon_id into v_conflict
  from public.draft_pool_team_roster_pokemon(p_season_id, p_team_id, p_drop_pokemon) r
  where public.draft_pool_species_keys(
          public.draft_pool_resolve_pokepedia_id(r.pokemon_id),
          r.pokemon_id
        ) && v_keys
  limit 1;

  if v_conflict is null then
    return;
  end if;

  v_display := coalesce(
    (
      select nullif(btrim(e.sheet_name), '')
      from public.draft_pool_published_entry_for_pokemon(p_season_id, v_conflict) e
      limit 1
    ),
    (select nullif(initcap(btrim(p.name)), '') from public.pokemon p where p.id = v_conflict),
    'that Pokemon'
  );

  raise exception 'SPECIES_CLAUSE' using detail = 'species=' || v_display;
end;
$$;

